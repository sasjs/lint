/**
 * Generates `src/utils/sasMacros.generated.ts` from the SAS language data.
 *
 * The list of macros that ship with SAS is not lint's to maintain: it is
 * language data, and `@sasjs/sas-language` owns it. This script reads the
 * `macroStatements` and `macroFunctions` groups and emits the names the
 * `noUndeclaredMacros` rule treats as declared.
 *
 * The output is committed so that the published package carries no dependency
 * on the data package, and `src/utils/sasMacros.spec.ts` regenerates the list
 * from the same data and fails when the two differ, so a refresh upstream
 * cannot leave the constant stale.
 *
 * Run with `npm run generate:macros`.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE = '@sasjs/sas-language'
const GROUPS = ['macroStatements', 'macroFunctions']
const TARGET = path.join(ROOT, 'src', 'utils', 'sasMacros.generated.ts')

const indexPath = (group) =>
  path.join(
    ROOT,
    'node_modules',
    ...PACKAGE.split('/'),
    'data',
    `${group}.index.json`
  )

/**
 * Every macro name a group carries, as a bare lower-case name. Compound
 * entries such as `%DO %UNTIL` are dropped: they are a spelling of the
 * `%DO` statement and no source token can match them.
 */
const collectMacroNames = async () => {
  const names = new Set()

  for (const group of GROUPS) {
    let parsed
    try {
      parsed = JSON.parse(await readFile(indexPath(group), 'utf8'))
    } catch (error) {
      throw new Error(
        `cannot read ${PACKAGE}/data/${group}.index.json - run 'npm install' first (${error.message})`
      )
    }

    if (!Array.isArray(parsed?.entries)) {
      throw new Error(
        `${PACKAGE}/data/${group}.index.json has an unexpected shape: expected { entries: [] }`
      )
    }

    for (const entry of parsed.entries) {
      const name = String(entry?.[0] ?? '')
        .replace(/^%/, '')
        .trim()
        .toLowerCase()
      if (!name || /\s/.test(name)) continue
      names.add(name)
    }
  }

  return [...names].sort()
}

/**
 * The generated file's text.
 */
const render = (names) =>
  [
    '// Generated by scripts/generate-macro-names.mjs from @sasjs/sas-language.',
    '// Do not edit. Regenerate with `npm run generate:macros`.',
    '',
    '/**',
    ' * The macro names that ship with SAS, lower-cased and without the leading',
    ' * `%`, as published in the macroStatements and macroFunctions groups of',
    ' * `@sasjs/sas-language`.',
    ' */',
    'export const sasMacros: readonly string[] = [',
    ...names.map((name) => `  '${name}',`),
    ']',
    ''
  ].join('\n')

const main = async () => {
  const names = await collectMacroNames()
  await writeFile(TARGET, render(names))
  console.log(
    `written: src/utils/sasMacros.generated.ts (${names.length} names)`
  )
}

main().catch((error) => {
  console.error(`generation failed: ${error.message}`)
  process.exit(1)
})
